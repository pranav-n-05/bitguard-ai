router = APIRouter(prefix="/alerts", tags=["alerts"])
Reader = Annotated[User, Depends(require("alert.read"))]


@router.get("", response_model=Paginated[AlertOut])
async def list_alerts(
    s: SessionDep,
    page: PageDep,
    _: Reader,
    status: Annotated[list[AlertStatus] | None, Query()] = None,
    severity: Annotated[list[Severity] | None, Query()] = None,
    category: Annotated[str | None, Query(max_length=64)] = None,
    assigned_to: uuid.UUID | None = None,
    unassigned: bool = False,
    q: Annotated[str | None, Query(max_length=100, description="txid / address / IP / title search")] = None,
    start: datetime | None = None,
    end: datetime | None = None,
) -> Paginated[AlertOut]:
    stmt = select(Alert)
    if status:
        stmt = stmt.where(Alert.status.in_(status))
    if severity:
        stmt = stmt.where(Alert.severity.in_(severity))
    if category:
        stmt = stmt.where(Alert.category == category)
    if assigned_to:
        stmt = stmt.where(Alert.assigned_to == assigned_to)
    if unassigned:
        stmt = stmt.where(Alert.assigned_to.is_(None))
    if q:
        stmt = stmt.where(
            or_(Alert.txid == q.lower(), Alert.entity_key == q, Alert.addresses.contains([q]), Alert.title.ilike(f"%{q}%"))
        )
    if start:
        stmt = stmt.where(Alert.created_at >= start)
    if end:
        stmt = stmt.where(Alert.created_at <= end)
    total = await s.scalar(select(func.count()).select_from(stmt.subquery())) or 0
    stmt = apply_sort(
        stmt,
        Alert,
        page.sort,
        {"created_at", "risk_score", "severity", "status", "category"},
        Alert.risk_score.desc().nulls_last(),
    )
    rows = (await s.execute(stmt.limit(page.limit).offset(page.offset))).scalars().all()
    return Paginated(items=[AlertOut.model_validate(a) for a in rows], total=total, limit=page.limit, offset=page.offset)


async def _detail(s: SessionDep, a: Alert) -> AlertDetail:
    notes = (await s.execute(select(AlertNote).where(AlertNote.alert_id == a.id).order_by(AlertNote.created_at))).scalars()
    rel = (
        await s.execute(
            select(Alert.id, Alert.category, Alert.severity, Alert.status, AlertLink.reason)
            .join(AlertLink, AlertLink.related_alert_id == Alert.id)
            .where(AlertLink.alert_id == a.id)
        )
    ).all()
    return AlertDetail(
        **AlertOut.model_validate(a).model_dump(),
        notes=[AlertNoteOut.model_validate(n) for n in notes],
        related_alerts=[
            {"id": str(r.id), "category": r.category, "severity": r.severity.value, "status": r.status.value, "reason": r.reason}
            for r in rel
        ],
        allowed_transitions=sorted(t.value for t in wf.TRANSITIONS[a.status]),
    )


@router.get("/{alert_id}", response_model=AlertDetail)
async def get_alert(alert_id: uuid.UUID, s: SessionDep, _: Reader) -> AlertDetail:
    return await _detail(s, await wf.get(s, alert_id))


@router.post("", response_model=AlertDetail, status_code=201, summary="Create a manual analyst alert")
async def create_alert(body: AlertCreate, s: SessionDep, user: Annotated[User, Depends(require("alert.create"))]) -> AlertDetail:
    if body.category not in wf.CATEGORIES:
        raise AppError(f"Unknown category; allowed: {sorted(wf.CATEGORIES)}")
    key = sha256_hex(f"manual|{body.category}|{body.entity_type}|{body.entity_key}|{uuid.uuid4()}")
    a = Alert(
        dedup_key=key,
        category=body.category,
        severity=body.severity,
        title=body.title,
        entity_type=body.entity_type,
        entity_key=body.entity_key,
        txid=body.txid,
        addresses=body.addresses,
        detection_method="analyst_manual",
        triggered_rules=[{"code": "MANUAL", "created_by": str(user.id)}],
        explanation=body.explanation,
        confidence="analyst",
        uncertainty_notes="Manually raised by an analyst; not generated by automated detection.",
    )
    s.add(a)
    await s.flush()
    await audit.record(
        s,
        "alert.created_manual",
        "alert",
        str(a.id),
        actor_id=user.id,
        actor_email=user.email,
        details=body.model_dump(mode="json"),
    )
    await s.commit()
    return await _detail(s, a)


@router.patch("/{alert_id}", response_model=AlertDetail)
async def patch_alert(
    alert_id: uuid.UUID, body: AlertPatch, s: SessionDep, user: Annotated[User, Depends(require("alert.acknowledge"))]
) -> AlertDetail:
    a = await wf.get(s, alert_id, lock=True)
    if body.assigned_to or body.unassign:
        await wf.assign(s, a, None if body.unassign else body.assigned_to, user)
    if body.severity and body.severity != a.severity:
        if "alert.resolve" not in user.permission_codes:
            raise PermissionDeniedError("Changing severity requires alert.resolve")
        await audit.record(
            s,
            "alert.severity_changed",
            "alert",
            str(a.id),
            actor_id=user.id,
            details={"from": a.severity.value, "to": body.severity.value},
        )
        a.severity = body.severity
    if body.status:
        await wf.transition(s, a, body.status, user, body.note)
    elif body.note:
        await wf.add_note(s, a, body.note, user)
    await s.commit()
    await s.refresh(a)
    return await _detail(s, a)


@router.post("/{alert_id}/acknowledge", response_model=AlertDetail)
async def acknowledge(
    alert_id: uuid.UUID, s: SessionDep, user: Annotated[User, Depends(require("alert.acknowledge"))]
) -> AlertDetail:
    a = await wf.get(s, alert_id, lock=True)
    await wf.transition(s, a, AlertStatus.acknowledged, user)
    if a.assigned_to is None:
        await wf.assign(s, a, user.id, user)
    await s.commit()
    await s.refresh(a)
    return await _detail(s, a)


@router.post("/{alert_id}/resolve", response_model=AlertDetail)
async def resolve(
    alert_id: uuid.UUID, body: ResolveRequest, s: SessionDep, user: Annotated[User, Depends(require("alert.resolve"))]
) -> AlertDetail:
    a = await wf.get(s, alert_id, lock=True)
    to = AlertStatus.false_positive if body.false_positive else AlertStatus.resolved
    await wf.transition(s, a, to, user, body.note, body.confirmed_suspicious)
    await s.commit()
    await s.refresh(a)
    return await _detail(s, a)
