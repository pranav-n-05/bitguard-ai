import uuid
from datetime import datetime
from typing import Annotated

from fastapi import APIRouter, Depends, Query
from sqlalchemy import func, or_, select

from app.alerts import workflow as wf
from app.api.deps import PageDep, SessionDep, apply_sort, require
from app.core.errors import AppError, PermissionDeniedError
from app.core.hashing import sha256_hex
from app.models import Alert, AlertLink, AlertNote, User
from app.models.base import AlertStatus, Severity
from app.schemas.alerts import AlertCreate, AlertDetail, AlertNoteOut, AlertOut, AlertPatch, ResolveRequest
from app.schemas.common import Paginated
