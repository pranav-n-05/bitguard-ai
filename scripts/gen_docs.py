#!/usr/bin/env python3
"""Generate docs/api/api.md (from the FastAPI OpenAPI schema) and docs/database/er-diagram.md (from SQLAlchemy metadata)."""

import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend"))
os.environ.setdefault("BITGUARD_STORAGE_DIR", "/tmp/bitguard-docs")  # noqa: S108

from app.main import app  # noqa: E402
from app.models import Base  # noqa: E402

PERM = {}


def api_md() -> str:
    spec = app.openapi()
    by_tag: dict[str, list[tuple[str, str, dict]]] = {}
    for path, ops in spec["paths"].items():
        for method, op in ops.items():
            by_tag.setdefault((op.get("tags") or ["other"])[0], []).append((method.upper(), path, op))
    out = [
        "# REST API reference",
        "",
        "Generated from the OpenAPI schema by `scripts/gen_docs.py` (live schema at `/api/v1/openapi.json`, "
        "interactive docs at `/api/docs` when enabled).",
        "",
        "* Base path: `/api/v1`. Auth: `Authorization: Bearer <access token>` (except `/health` and `/auth/login|refresh`).",
        "* Errors: RFC 9457 `application/problem+json` with `request_id`; internals are never leaked.",
        "* Lists: `limit` (1-500), `offset`, `sort` (`field` or `-field`, allow-listed per endpoint) and endpoint-specific filters; "
        "responses are `{items,total,limit,offset}`.",
        "* Rate limits: login 10/min/IP, default 600/min/IP (configurable). Request bodies: JSON 1 MiB, uploads 512 MiB.",
        "",
    ]
    for tag in sorted(by_tag):
        out += [f"## {tag}", "", "| Method | Path | Summary |", "|---|---|---|"]
        for m, p, op in sorted(by_tag[tag], key=lambda x: (x[1], x[0])):
            summary = (op.get("summary") or op.get("operationId", "")).replace("|", "/")
            out.append(f"| {m} | `/api/v1{p}` | {summary} |")
        out.append("")
    return "\n".join(out)


def er_md() -> str:
    out = [
        "# Database design",
        "",
        "PostgreSQL 16, SQLAlchemy 2.0, Alembic migrations (`backend/migrations`). Generated by `scripts/gen_docs.py`.",
        "",
        "Rules: monetary values are `BIGINT` satoshis; all timestamps are UTC `timestamptz`; `txid`, address, time, IP, ASN, "
        "block height, alert status and case FKs are indexed; duplicate ingestion is prevented by unique constraints "
        "(`transactions.txid`, `raw_records(dataset_file_id, record_index)`, `network_observations.obs_hash`, "
        "`dataset_files(dataset_id, sha256)`). `audit_logs`, `raw_records` and `evidence_records` are append-only "
        "(trigger raises on UPDATE/DELETE). Partitioning is intentionally not used: measured data volume does not justify it.",
        "",
        "```mermaid",
        "erDiagram",
    ]
    for t in Base.metadata.sorted_tables:
        for fk in t.foreign_keys:
            out.append(f"    {fk.column.table.name} ||--o{{ {t.name} : \"{next(iter(fk.constraint.column_keys))}\"")
    out.append("```")
    out += ["", "## Tables", ""]
    for t in Base.metadata.sorted_tables:
        out += [f"### `{t.name}`", "", "| Column | Type | Null | Key |", "|---|---|---|---|"]
        for c in t.columns:
            key = "PK" if c.primary_key else ("FK" if c.foreign_keys else ("UQ" if c.unique else ""))
            out.append(f"| {c.name} | {c.type!s} | {'yes' if c.nullable else 'no'} | {key} |")
        idx = [i.name for i in t.indexes]
        if idx:
            out += ["", "Indexes: " + ", ".join(f"`{i}`" for i in sorted(idx))]
        out.append("")
    return "\n".join(out)


if __name__ == "__main__":
    (ROOT / "docs/api/api.md").write_text(api_md())
    (ROOT / "docs/database/er-diagram.md").write_text(er_md())
    print("docs generated")
